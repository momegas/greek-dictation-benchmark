/**
 * The department corpus: 100 longer utterances across the functions a Greek company has.
 *
 * Two things differ from the first corpus (`utterances.ts`):
 *   1. Length. These are 2-5 sentence passages, the shape of real dictation, so they also
 *      test drift and punctuation over distance rather than single-clause accuracy.
 *   2. Voice and provider diversity. Each utterance declares whether it contains figures;
 *      `hasNumbers` routes synthesis to grok-tts, which reads Greek digits reliably, while
 *      prose-only passages go to openai/tts-1. That routing is a measured decision, not a
 *      preference: on number-bearing text openai/tts-1 loses digits that four independent
 *      STT engines then all mis-hear the same way, which is the signature of bad audio
 *      rather than bad transcription.
 *
 * Numbers are written plainly — no thousands separators, no decimal comma, percentages
 * spelled as "τοις εκατό" — because the separators were themselves a source of TTS
 * ambiguity. The written reference matches how the figure is spoken.
 */
import type { Entity } from "../lib/metrics";

export type Dept =
  | "legal" | "finance" | "accounting" | "marketing" | "sales"
  | "technical" | "hr" | "operations" | "procurement" | "support" | "freelance";

export interface DeptUtterance {
  id: string;
  dept: Dept;
  /** Drives TTS routing: figures go to grok-tts. */
  hasNumbers: boolean;
  text: string;
  /**
   * Spoken-numeral reading, where the voice says the figure in words. A digit/word mismatch
   * is a formatting choice, not a transcription error, so both readings score as correct.
   */
  spoken?: string;
  /** Force a provider, overriding the hasNumbers routing. */
  forceGrok?: boolean;
  /**
   * Further acceptable readings. grok-tts is non-deterministic on large figures — the same
   * clip has come back as "84000", "84 χιλιάδες" and the fully spelled-out form across
   * runs — so a clip may legitimately be spoken more than one way.
   */
  altRefs?: string[];
  entities: Entity[];
}

